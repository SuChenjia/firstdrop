_UNKNOWN = "其他"
_SMOOTH = 2.0  # 置信度平滑项

# 构建时去重（同一词可能出现在多类别里，保留首次出现）
_LEXICON: dict[str, tuple[str, ...]] = {
    cat: tuple(dict.fromkeys(kws)) for cat, kws in CATEGORY_LEXICON.items()
}
# 每类关键词按长度降序，保证"最长匹配优先"
_SORTED: dict[str, list[str]] = {
    cat: sorted((k.lower() for k in kws), key=len, reverse=True)
    for cat, kws in _LEXICON.items()
}


def categories() -> list[str]:
    """全部行业标签（含兜底"其他"）。"""
    return list(_LEXICON.keys()) + [_UNKNOWN]


def classify(title: str | None) -> tuple[str, float]:
    """轻量文本分类：返回 (类别, 置信度)。无任何命中时返回 ("其他", 0.0)。"""
    text = (title or "").lower()
    if not text:
        return _UNKNOWN, 0.0

    scores: dict[str, int] = {}
    longest: dict[str, int] = {}
    for cat, kws in _SORTED.items():
        probe = text
        s = 0
        top = 0
        for kw in kws:
            if kw in probe:
                s += len(kw)
                top = max(top, len(kw))
                probe = probe.replace(kw, " ")  # 片段屏蔽：避免子串重复计分
        if s:
            scores[cat] = s
            longest[cat] = top

    if not scores:
        return _UNKNOWN, 0.0

    # 得分优先，其次比较命中的最长关键词（更长者更具体）
    ranked = sorted(scores.items(), key=lambda kv: (kv[1], longest[kv[0]]), reverse=True)
    cat, top = ranked[0]
    second = ranked[1][1] if len(ranked) > 1 else 0
    conf = top / (top + second + _SMOOTH)
    return cat, round(min(conf, 0.99), 2)
