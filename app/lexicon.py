def _meaningful_ratio(text: str) -> float:
    """有意义字符（中文/字母/数字）占比。"""
    s = _CONTROL.sub("", text or "")
    if not s:
        return 0.0
    keep = _ALLOWED.findall(s)
    return len(keep) / len(s)


def check_filter(title: str | None, norm_title: str | None) -> tuple[bool, str | None]:
    """清洗过滤判定。

    返回 (ok, reason)：ok=False 表示应过滤，reason 为过滤原因。
    判定顺序：无效字符 → 过短 → 广告词 → 敏感词。
    """
    nt = norm_title or ""
    if not nt:
        return False, "空词"
    if not _ALLOWED.search(nt):
        return False, "无效字符"
    if len(nt) < MIN_LEN:
        return False, "过短"
    if _meaningful_ratio(title or nt) < 0.3:
        return False, "无效字符"

    low = (title or "").lower()
    for w in AD_WORDS:
        if w in low:
            return False, f"广告词:{w}"
    for w in SENSITIVE_WORDS:
        if w in low:
            return False, f"敏感词:{w}"
    return True, None


